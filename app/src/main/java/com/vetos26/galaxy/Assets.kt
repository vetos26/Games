package com.vetos26.galaxy

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.media.AudioAttributes
import android.media.SoundPool

/** Loads PNG sprites from assets/sprites one by one, so the loading screen can show progress. */
class Assets(private val context: Context) {

    private val names = listOf(
        "player",
        "enemy_flagship_1", "enemy_flagship_2",
        "enemy_red_1", "enemy_red_2",
        "enemy_purple_1", "enemy_purple_2",
        "enemy_blue_1", "enemy_blue_2",
        "bullet_player", "bullet_enemy",
        "explosion_1", "explosion_2", "explosion_3", "explosion_4",
        "explosion_player_1", "explosion_player_2", "explosion_player_3", "explosion_player_4",
        "flag",
        "btn_left", "btn_left_on", "btn_right", "btn_right_on", "btn_fire", "btn_fire_on", "btn_pause",
    )

    private val bitmaps = HashMap<String, Bitmap>()
    private var index = 0

    /** Logo is needed immediately for the loading screen. */
    val logo: Bitmap = decode("logo.png")

    val progress: Float get() = index.toFloat() / names.size
    val done: Boolean get() = index >= names.size

    /** Loads the next sprite. Returns true when everything is loaded. */
    fun loadNext(): Boolean {
        if (index < names.size) {
            val n = names[index]
            bitmaps[n] = decode("sprites/$n.png")
            index++
        }
        return done
    }

    operator fun get(name: String): Bitmap = bitmaps[name] ?: error("Sprite not loaded: $name")

    private fun decode(path: String): Bitmap {
        val opts = BitmapFactory.Options().apply {
            inScaled = false
            inPreferredConfig = Bitmap.Config.ARGB_8888
        }
        return context.assets.open(path).use { BitmapFactory.decodeStream(it, null, opts) }
            ?: error("Cannot decode $path")
    }
}

/** 8-bit style sound effects (generated by tools/make_assets.py). */
class Sound(context: Context) {
    private val pool: SoundPool = SoundPool.Builder()
        .setMaxStreams(8)
        .setAudioAttributes(
            AudioAttributes.Builder()
                .setUsage(AudioAttributes.USAGE_GAME)
                .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                .build()
        )
        .build()

    val shoot = pool.load(context, R.raw.sfx_shoot, 1)
    val hit = pool.load(context, R.raw.sfx_hit, 1)
    val die = pool.load(context, R.raw.sfx_die, 1)
    val dive = pool.load(context, R.raw.sfx_dive, 1)
    val start = pool.load(context, R.raw.sfx_start, 1)
    val extra = pool.load(context, R.raw.sfx_extra, 1)
    val clear = pool.load(context, R.raw.sfx_clear, 1)
    val menu = pool.load(context, R.raw.sfx_menu, 1)

    var enabled = true

    fun play(id: Int, volume: Float = 0.8f) {
        if (enabled) pool.play(id, volume, volume, 1, 0, 1f)
    }

    fun stopAll() = pool.autoPause()
    fun resumeAll() = pool.autoResume()
    fun release() = pool.release()
}
