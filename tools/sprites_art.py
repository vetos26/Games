# Galaxian-style "bug" with flapping wings. Two frames (wings up / down).
def drone(body, dark, wing, wing_dark, eye='Y'):
    up = [
        "................",
        "................",
        "................",
        "................",
        "...........d....",
        "............d...",
        "..W..........b..",
        "..WW.........bbb",
        "..wWW.......bbbb",
        "..wWWW......bEbb",
        "...wWWW.....bbbb",
        "...wwWWW....bbbb",
        "....wwWWW..bbbbb",
        ".....wwWWWbbbbbb",
        "......wwWbbbbbbb",
        ".......wbbbbbbbb",
        "........ddbbbbbb",
        "..........dbbbbb",
        "...........dbbbb",
        "............dbbb",
        ".............dbb",
        "..............db",
        "...............d",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
    ]
    down = [
        "................",
        "................",
        "................",
        "................",
        "...........d....",
        "............d...",
        ".............b..",
        ".............bbb",
        "............bbbb",
        "............bEbb",
        "............bbbb",
        "............bbbb",
        "...........bbbbb",
        "........wwbbbbbb",
        ".....wwwWWbbbbbb",
        "...wwWWWWWbbbbbb",
        "..wWWWWWWddbbbbb",
        ".wWWWWWw...dbbbb",
        ".WWWWw......dbbb",
        ".WWw.........dbb",
        ".W............db",
        "...............d",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
        "................",
    ]

    def recolor(rows):
        out = []
        for r in rows:
            r = r.replace('W', wing).replace('w', wing_dark)
            r = r.replace('b', body).replace('d', dark).replace('E', eye)
            out.append(r)
        return out

    return recolor(up), recolor(down)


